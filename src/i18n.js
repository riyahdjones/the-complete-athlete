const dictionaries = { es: { ...generatedSpanish, ...es } };

function normalizeLanguage(value) {
  return String(value || '').toLowerCase().startsWith('es') ? 'es' : 'en';
}

export function getInitialLanguage() {
  if (typeof window === 'undefined') return 'en';
  try {
    const saved = localStorage.getItem(languageStorageKey);
    if (saved) return normalizeLanguage(saved);
  } catch {
    // Browser storage is optional.
  }
  return normalizeLanguage(navigator.language);
}

export function saveLanguagePreference(language) {
  const normalized = normalizeLanguage(language);
  try { localStorage.setItem(languageStorageKey, normalized); } catch { /* optional */ }
  if (typeof document !== 'undefined') document.documentElement.lang = normalized;
  return normalized;
}

export function translateText(value, language = 'en') {
  const original = String(value ?? '');
  if (normalizeLanguage(language) === 'en' || !original.trim()) return original;
  const leading = original.match(/^\s*/)?.[0] || '';
  const trailing = original.match(/\s*$/)?.[0] || '';
  const clean = original.trim();
  if (/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(clean)) return original;
  if (['App Review Parent', 'App Review Athlete'].includes(clean)) return original;
  const direct = dictionaries.es[clean];
  if (direct) return `${leading}${direct}${trailing}`;

  let result = clean
    .replace(/^Good morning,\s*/i, 'Buenos días, ')
    .replace(/^Good afternoon,\s*/i, 'Buenas tardes, ')
    .replace(/^Good evening,\s*/i, 'Buenas noches, ')
    .replace(/^Hello,\s*/i, 'Hola, ')
    .replace(/^(\d+) Days$/i, '$1 Días')
    .replace(/^(\d+) Day$/i, '$1 Día')
    .replace(/^(\d+) points?$/i, '$1 puntos')
    .replace(/^(\d+) goals?$/i, '$1 metas')
    .replace(/^(\d+) of (\d+) complete$/i, '$1 de $2 completadas')
    .replace(/^(\d+) linked$/i, '$1 vinculados')
    .replace(/^(\d+) lessons? completed$/i, '$1 lecciones completadas')
    .replace(/^Age\s+(\d+)/i, 'Edad $1')
    .replace(/^DAY (\d+) OF (\d+)$/i, 'DÍA $1 DE $2')
    .replace(/^DAY (\d+)$/i, 'DÍA $1');
  return `${leading}${result}${trailing}`;
}

const translatedTextNodes = new WeakMap();
const translatedAttributes = new WeakMap();
const translatableAttributes = ['placeholder', 'aria-label', 'title'];

function translateElementTree(root, language) {
  if (!root) return;
  const elements = root.nodeType === Node.ELEMENT_NODE ? [root] : [];
  if (root.querySelectorAll) elements.push(...root.querySelectorAll('*'));
  elements.forEach((element) => {
    if (['SCRIPT', 'STYLE', 'TEXTAREA'].includes(element.tagName) || element.closest('[translate="no"], [contenteditable="true"]')) return;
    let attributeOriginals = translatedAttributes.get(element);
    if (!attributeOriginals) {
      attributeOriginals = {};
      translatedAttributes.set(element, attributeOriginals);
    }
    translatableAttributes.forEach((attribute) => {
      if (!element.hasAttribute(attribute)) return;
      const current = element.getAttribute(attribute);
      const previous = attributeOriginals[attribute];
      const original = previous && current === previous.rendered ? previous.original : current;
      const rendered = translateText(original, language);
      attributeOriginals[attribute] = { original, rendered };
      if (current !== rendered) element.setAttribute(attribute, rendered);
    });
    element.childNodes.forEach((node) => {
      if (node.nodeType !== Node.TEXT_NODE || !node.nodeValue?.trim()) return;
      const previous = translatedTextNodes.get(node);
      const original = previous && node.nodeValue === previous.rendered ? previous.original : node.nodeValue;
      const translated = translateText(original, language);
      translatedTextNodes.set(node, { original, rendered: translated });
      if (node.nodeValue !== translated) node.nodeValue = translated;
    });
  });
}

export function installDocumentTranslation(language) {
  if (typeof document === 'undefined') return () => {};
  let translating = false;
  const apply = (root = document.body) => {
    if (translating) return;
    translating = true;
    translateElementTree(root, language);
    translating = false;
  };
  apply();
  const observer = new MutationObserver((mutations) => {
    if (translating) return;
    mutations.forEach((mutation) => {
      if (mutation.type === 'attributes') {
        apply(mutation.target);
        return;
      }
      if (mutation.type === 'characterData' && mutation.target.parentElement) {
        apply(mutation.target.parentElement);
        return;
      }
      mutation.addedNodes.forEach((node) => {
        if (node.nodeType === Node.ELEMENT_NODE) apply(node);
        else if (node.nodeType === Node.TEXT_NODE && node.parentElement) apply(node.parentElement);
      });
    });
  });
  observer.observe(document.body, { childList: true, characterData: true, subtree: true, attributes: true, attributeFilter: translatableAttributes });
  return () => observer.disconnect();
}

function localizedField(item, camel, snake) {
  return item?.[camel] ?? item?.[snake];
}

export function localizePlans(plans, language = 'en', spanishPlans = {}, sourcePlans = []) {
  if (normalizeLanguage(language) !== 'es') return plans;
  return (plans || []).map((plan) => {
    // A published database lesson can have a UUID instead of its seed ID.
    // Only reuse a translation when the source content still matches exactly.
    const source = sourcePlans.find((candidate) => candidate.title === plan.title && candidate.subject === plan.subject && JSON.stringify(candidate.steps) === JSON.stringify(plan.steps));
    const asset = spanishPlans?.[String(source?.id || plan.id)] || {};
    const title = localizedField(plan, 'titleEs', 'title_es') || asset.title;
    const subject = localizedField(plan, 'subjectEs', 'subject_es') || asset.subject;
    const remoteSteps = localizedField(plan, 'stepsEs', 'steps_es');
    const steps = Array.isArray(remoteSteps) && remoteSteps.length ? remoteSteps : asset.steps;
    const challengeDay = localizedField(plan, 'challengeDayEs', 'challenge_day_es') || asset.challengeDay;
    return {
      ...plan,
      titleEn: plan.titleEn || plan.title,
      subjectEn: plan.subjectEn || plan.subject,
      ...(title ? { title } : {}),
      ...(subject ? { subject } : {}),
      ...(Array.isArray(steps) && steps.length ? { steps } : {}),
      ...(challengeDay ? { challengeDay } : {})
    };
  });
}
